import os
import tempfile
import unittest

import rescue_job as rj


def synth_gcode():
    """Two layers of a square ring (10..30) with a retraction/wipe/hop between beads. Absolute, relative E."""
    L = ["; generated by OrcaSlicer test", "; total layer number: 3", "; HEADER_BLOCK_END", "",
         "M140 S60", "M104 S220", "EXCLUDE_OBJECT_DEFINE NAME=Part CENTER=20,20", "SET_PRESSURE_ADVANCE ADVANCE=0.08",
         "SET_VELOCITY_LIMIT ACCEL=2500 ACCEL_TO_DECEL=1750", "M106 S255", "G90", "M83", "EXCLUDE_OBJECT_START NAME=Part"]
    for z in (0.2, 0.4):
        L += [";LAYER_CHANGE", ";Z:%s" % z, "G1 Z%s F600" % z, "G1 X10 Y10 F12000"]
        for k in range(1, 21):
            L.append("G1 X%s Y10 E.05 F6000" % (10 + k))
        for k in range(1, 21):
            L.append("G1 X30 Y%s E.05" % (10 + k))
        L += ["G1 E-.4 F3000", ";WIPE_START", "G1 X29 Y29 E-.1", ";WIPE_END", "G1 X20 Y20 Z%s F12000" % (z + 0.4), "G1 Z%s" % z, "G1 E.5 F3000"]
    L += ["M104 S0", "M140 S0", ""]
    return L


class TestLogParsing(unittest.TestCase):
    def test_last_exit_and_position_win(self):
        t = ("Exiting SD card print (position 100)\n"
             "gcode state: a=1 last_position=[1.0, 2.0, 3.0, 4.0] x=2\n"
             "Exiting SD card print (position 250)\n"
             "gcode state: a=1 last_position=[130.733, 130.362, 82.0, 6356.7] x=2\n")
        s = rj.parse_stop_state(t)
        self.assertEqual(s["exit_pos"], 250)
        self.assertEqual(s["last_position"], [130.733, 130.362, 82.0])

    def test_no_exit_line_gives_none(self):
        self.assertIsNone(rj.parse_stop_state("nothing here")["exit_pos"])


class TestGeometry(unittest.TestCase):
    def test_envelope_uses_extrusions_only(self):
        env = rj.part_envelope(synth_gcode())
        # the travel to X20 Y20 at the layer change and the wipe point do not count (no positive E on those moves)
        self.assertEqual((env["x0"], env["x1"], env["y0"], env["y1"]), (11.0, 30.0, 10.0, 30.0))
        self.assertEqual(env["top"], 0.4)

    def test_envelope_rejects_a_file_without_extrusion(self):
        with self.assertRaises(rj.JobError):
            rj.part_envelope(["G1 X1 Y1", "G1 X2 Y2"])

    def test_line_of_offset_requires_a_line_boundary(self):
        data = b"G1 X1\nG1 X2\n"
        self.assertEqual(rj.line_of_offset(data, 6), 1)
        with self.assertRaises(rj.JobError):
            rj.line_of_offset(data, 4)


class TestResumeLine(unittest.TestCase):
    def test_an_overlap_reaching_before_the_file_start_is_a_refusal_not_a_traceback(self):
        lines = ["G1 X10 Y10 E1.0", "G1 X11 Y10 E1.0", "G1 X12 Y10 E1.0"]
        with self.assertRaises(rj.JobError):
            rj.pick_resume_line(lines, 1, 10 ** 6)

    def setUp(self):
        self.lines = synth_gcode()
        # exit on the hop travel of layer 2 (the 'G1 X20 Y20 Z0.8 F12000' line)
        self.exit_idx = max(i for i, l in enumerate(self.lines) if l.startswith("G1 X20 Y20 Z"))

    def test_picks_a_plain_extrusion_not_a_retraction(self):
        i = rj.pick_resume_line(self.lines, self.exit_idx, 40)
        self.assertRegex(self.lines[i], r"^G1 X[\d.]+ Y[\d.]+ E[\d.]+$")
        self.assertNotIn("E-", self.lines[i])

    def test_more_overlap_never_moves_the_line_forward(self):
        a = rj.pick_resume_line(self.lines, self.exit_idx, 40)
        b = rj.pick_resume_line(self.lines, self.exit_idx, 400)
        self.assertLessEqual(b, a)

    def test_park_point_is_the_end_of_the_previous_xy_move(self):
        i = rj.pick_resume_line(self.lines, self.exit_idx, 40)
        x, y = rj.park_point(self.lines, i)
        import re
        m = re.match(r"^G1 X([\d.]+) Y([\d.]+)", self.lines[i - 1])
        self.assertEqual((x, y), (float(m.group(1)), float(m.group(2))))

    def test_layer_state_and_temperatures(self):
        i = rj.pick_resume_line(self.lines, self.exit_idx, 40)
        ls = rj.layer_state(self.lines, i)
        self.assertEqual((ls["layer_index"], ls["layer_z"], ls["total_layers"]), (2, 0.4, 3))
        self.assertEqual(rj.temps_before(self.lines, i), (60, 220))


class TestResumeFile(unittest.TestCase):
    def setUp(self):
        self.lines = synth_gcode()
        exit_idx = max(i for i, l in enumerate(self.lines) if l.startswith("G1 X20 Y20 Z"))
        self.i = rj.pick_resume_line(self.lines, exit_idx, 40)
        self.out = rj.build_resume(self.lines, self.i, 60, 220)

    def test_preamble_has_no_motion_heating_mesh_or_probe(self):
        pre = self.out[:next(k for k, l in enumerate(self.out) if l.startswith(rj.MARKER))]
        for l in pre:
            self.assertFalse(l.startswith(("G28", "G29", "G1 X", "G1 Z", "BED_MESH", "PROBE", "M109", "M190", "START_PRINT")), l)
        text = "\n".join(pre)
        for need in ("CANCEL_PRINTER_SHUTDOWN", "M140 S60", "M104 S220", "EXCLUDE_OBJECT_START NAME=Part", "SET_PRESSURE_ADVANCE", "M106 S255",
                     "SET_PRINT_STATS_INFO TOTAL_LAYER=3 CURRENT_LAYER=2", "; total layer number: 3"):
            self.assertIn(need, text)

    def test_first_original_line_is_the_resume_line_and_layer_counter_follows(self):
        k = next(k for k, l in enumerate(self.out) if l.startswith(rj.MARKER))
        self.assertEqual(self.out[k + 1], self.lines[self.i])
        self.assertIn("%d ---" % (self.i + 1), self.out[k])

    def test_numbers_map_back_through_the_marker_and_skip_inserted_lines(self):
        nums = rj.to_original_numbers(self.out)
        k = next(k for k, l in enumerate(self.out) if l.startswith(rj.MARKER))
        self.assertEqual(nums[k + 1], self.i + 1)
        # the last original line keeps its original number even though SET_PRINT_STATS_INFO lines were inserted
        self.assertEqual(nums[len(self.out) - 1], len(self.lines))


class TestBuildJob(unittest.TestCase):
    def test_round_trip_from_a_resume_file(self):
        d = tempfile.mkdtemp()
        orig = os.path.join(d, "orig.gcode")
        lines = synth_gcode()
        with open(orig, "w") as f:
            f.write("\n".join(lines))
        exit_idx = max(i for i, l in enumerate(lines) if l.startswith("G1 X20 Y20 Z"))
        data = ("\n".join(lines[:exit_idx + 1]) + "\n").encode()
        exit_pos = len(data)
        job, resume = rj.build_job(orig, None, None, exit_pos, 1.0, 40.0, "resume.gcode")
        self.assertEqual(job["stop"]["exit_line_original"], exit_idx + 1)
        self.assertEqual(job["temps"], {"bed": 60, "nozzle": 220, "source": job["temps"]["source"]})
        self.assertEqual(job["part"]["top"], 0.4)
        # a second stop inside the resume file maps back to the original numbering
        rf = os.path.join(d, "resume.gcode")
        with open(rf, "w") as f:
            f.write("\n".join(resume))
        with open(rf) as f:
            rl = f.read().split("\n")
        idx = max(i for i, l in enumerate(rl) if l.startswith("G1 X20 Y20 Z"))
        pos2 = len(("\n".join(rl[:idx + 1]) + "\n").encode())
        job2, _ = rj.build_job(orig, None, rf, pos2, 1.0, 40.0, "resume2.gcode")
        self.assertEqual(job2["stop"]["exit_line_original"], exit_idx + 1)

    def test_exit_not_on_a_line_boundary_is_refused(self):
        d = tempfile.mkdtemp()
        orig = os.path.join(d, "o.gcode")
        with open(orig, "w") as f:
            f.write("\n".join(synth_gcode()))
        with self.assertRaises(rj.JobError):
            rj.build_job(orig, None, None, 7, 1.0, 40.0, "r.gcode")

    def test_file_rate_from_polls(self):
        d = tempfile.mkdtemp()
        p = os.path.join(d, "poll.csv")
        rows = ["time,state,klippy,progress,file_pos,z,hotend,bed"] + ["10:%02d:%02d,printing,ready,1,%d,5,220,60" % (k // 6, (k % 6) * 10, 1000 + 500 * k) for k in range(12)]
        with open(p, "w") as f:
            f.write("\n".join(rows))
        self.assertAlmostEqual(rj.file_rate(p, window_s=100), 50.0, places=3)


